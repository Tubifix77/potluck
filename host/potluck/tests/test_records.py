def test_every_fixture_line_is_valid_json_with_a_type():
    for line in _fixture_lines():
        obj = json.loads(line)  # raises if the firmware emitted anything malformed
        assert isinstance(obj, dict)
        assert "t" in obj, obj


def test_the_stream_recognises_every_record_the_firmware_emits():
    stream = RecordStream()
    kinds: list[str] = []
    for line in _fixture_lines():
        item = stream.feed(line)
        assert isinstance(item, Record), f"not recognised as a record: {line[:80]}"
        kinds.append(item.kind)

    assert stream.stats.bad_json == 0
    assert stream.stats.logs == 0
    # An unrecognised record type means the firmware emits something this tool
    # would silently ignore.
    assert stream.stats.unknown_kinds == {}, stream.stats.unknown_kinds
    assert set(kinds) == {"boot", "link", "node", "event"}


def test_boot_record_carries_the_section_6_measurement():
    stream = RecordStream()
    boot = next(
        item for line in _fixture_lines()
        if isinstance(item := stream.feed(line), Record) and item.kind == "boot"
    )
    dram = boot["dram"]
    # The derived figures are computed on the node so the host cannot get the
    # subtraction backwards; check they agree with the raw readings anyway.
    assert dram["wifi_stack"] == dram["after_netif"] - dram["after_wifi_start"]
    assert dram["espnow"] == dram["after_wifi_start"] - dram["after_espnow"]
    assert dram["total_to_radio"] == dram["at_boot"] - dram["after_espnow"]
    # section 8.2's numbers survive the round trip.
    assert boot["hb_period_ms"] == 100
    assert boot["hb_miss_limit"] == 6
    assert boot["hb_period_ms"] * boot["hb_miss_limit"] == 600


def test_link_record_never_claims_a_one_way_delay():
    # The commitment in firmware/components/pot_link/include/pot/link_stats.hpp,
    # checked against the emitted bytes rather than against the source comment.
    for line in _fixture_lines():
        obj = json.loads(line)
        if obj.get("t") != "link":
            continue
        text = json.dumps(obj)
        for forbidden in ("one_way", "oneway", "owd", "latency_us"):
            assert forbidden not in text, f"{forbidden} appeared in a link record"
        rtt = obj["rtt"]
        # Every duration names the clock it was measured on.
        assert "remote_turnaround_us" in rtt
        assert "txq_last_us" in rtt


def test_unmeasured_values_arrive_as_null_and_stay_none():
    stream = RecordStream()
    fresh = [
        item for line in _fixture_lines()
        if isinstance(item := stream.feed(line), Record)
        and item.kind == "link"
        and item.get("state") == "known"
    ]
    assert fresh, "the fixture should include a link with nothing measured yet"
    v = fresh[0]
    assert v["tx"]["pdr_ppm"] is None
    assert v["rx"]["pdr_ppm"] is None
    assert v["rtt"]["min_us"] is None
    assert v["rtt"]["p50_us"] is None
    # And a None ratio must not become 0.0% on the way to the display.
    assert ppm_to_percent(v["tx"]["pdr_ppm"]) is None
    assert ppm_to_percent(0) == 0.0  # a measured zero is still zero


def test_percentiles_agree_with_the_firmwares_own_computation():
    # The node ships bucket counts and its own p50/p99. Recomputing them here from
    # the counts is what keeps link_stats.py's bucket edges in step with the
    # firmware's: if the edges drifted, these would disagree.
    stream = RecordStream()
    checked = 0
    for line in _fixture_lines():
        item = stream.feed(line)
        if not isinstance(item, Record) or item.kind != "link":
            continue
        rtt = item["rtt"]
        hist = rtt.get("hist")
        if not hist or sum(hist) == 0:
            continue
        for pct, key in ((50, "p50_us"), (99, "p99_us")):
            ours = ls.percentile(hist, pct)
            theirs = rtt[key]
            assert ours is not None and theirs is not None
            assert list(ours) == list(theirs), f"p{pct}: host {ours} vs node {theirs}"
        checked += 1
    assert checked > 0, "no populated histogram in the fixture"


def test_ppm_conversion():
    assert ppm_to_percent(1_000_000) == 100.0
    assert ppm_to_percent(991_983) == 99.1983
    assert ppm_to_percent(None) is None


