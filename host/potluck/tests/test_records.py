def test_monitor_summary_reports_what_section_13_M0_asks_for():
    monitor = Monitor()
    stream = RecordStream()
    for line in _fixture_lines():
        item = stream.feed(line)
        if isinstance(item, Record):
            monitor.on_record(item.kind, item.data)

    text = monitor.summary()

    # A PDR figure and a delay histogram, both measured.
    assert "PDR" in text
    assert "delay histogram" in text
    assert "2.0-3.0 ms" in text  # a populated bucket, rendered from its edges
    # section 6's [MEASURE] item.
    assert "[MEASURE]" in text
    assert "Wi-Fi stack cost" in text
    # And the honesty note travels with the histogram.
    assert "no one-way measurement" in text
    assert "one_way" not in text.replace("no one-way measurement", "")
    # An unmeasured link says so rather than reporting zero.
    assert "unmeasured" in text


def test_monitor_surfaces_membership_transitions_immediately():
    monitor = Monitor()
    out = monitor.on_record("event", {"at_ms": 601, "node": 258, "kind": "peer_dead",
                                      "peer": 0xCDEF, "slot": 0, "a": 6, "b": 600})
    assert out is not None and "peer_dead" in out
    # A routine event should not interrupt the display.
    assert monitor.on_record("event", {"at_ms": 1, "node": 258, "kind": "peer_discovered",
                                       "peer": 1, "slot": 0, "a": 0, "b": 0}) is None


def test_monitor_boot_line_flags_a_wifi_stack_over_section_6s_expectation():
    monitor = Monitor()
    out = monitor.on_record("boot", {
        "node": 1, "epoch": 1, "mac": "aa:bb:cc:dd:ee:ff", "espnow_ver": 2, "chan": 1,
        "hb_period_ms": 100, "hb_miss_limit": 6, "fw": "m0", "idf": "v6.0.2",
        "dram": {"wifi_stack": 50 * 1024, "espnow": 2048},
    })
    assert out is not None and "ABOVE" in out and "RX ring shrinks first" in out

    ok = monitor.on_record("boot", {
        "node": 2, "epoch": 1, "mac": "aa:bb:cc:dd:ee:00", "espnow_ver": 2, "chan": 1,
        "hb_period_ms": 100, "hb_miss_limit": 6, "fw": "m0", "idf": "v6.0.2",
        "dram": {"wifi_stack": 30 * 1024, "espnow": 2048},
    })
    assert ok is not None and "ABOVE" not in ok


def test_monitor_table_renders_with_no_data_and_with_data():
    monitor = Monitor()
    assert "no links yet" in monitor.table()
    stream = RecordStream()
    for line in _fixture_lines():
        item = stream.feed(line)
        if isinstance(item, Record):
            monitor.on_record(item.kind, item.data)
    table = monitor.table()
    assert "0x0102" in table
    assert "--" in table  # the unmeasured link's PDR


