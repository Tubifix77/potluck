def test_bucket_edges_are_monotonic_and_cover_everything():
    for i in range(1, ls.RTT_BUCKETS):
        assert ls.RTT_BUCKET_EDGE_US[i] > ls.RTT_BUCKET_EDGE_US[i - 1]
    assert ls.RTT_BUCKET_EDGE_US[-1] == 0xFFFFFFFF
    assert ls.bucket_bounds(0) == (0, 1000)
    assert ls.bucket_bounds(ls.RTT_BUCKETS - 1)[1] is None


def test_bucket_of_matches_the_firmware_rule():
    # A sample equal to an edge belongs to that bucket; one more goes to the next.
    assert ls.bucket_of(0) == 0
    assert ls.bucket_of(1000) == 0
    assert ls.bucket_of(1001) == 1
    assert ls.bucket_of(2000) == 1
    assert ls.bucket_of(500_000) == ls.RTT_BUCKETS - 1
    # section 3's measured figures all land inside the finite range.
    for us in (2783, 3462, 7851, 25628, 59192, 103850):
        assert ls.bucket_of(us) < ls.RTT_BUCKETS - 1


def test_percentile_is_an_interval_and_empty_is_none():
    assert ls.percentile([0] * 16, 50) is None
    h = [0] * 16
    h[2] = 90    # (2000, 3000]
    h[11] = 10   # (42000, 60000]
    assert ls.percentile(h, 50) == (2000, 3000)
    assert ls.percentile(h, 90) == (2000, 3000)
    assert ls.percentile(h, 99) == (42000, 60000)
    assert ls.percentile(h, 100) == (42000, 60000)


def test_mean_is_bounded_not_invented():
    h = [0] * 16
    h[2] = 1  # (2000, 3000]
    lo, hi = ls.mean_bounds(h)
    assert lo == 2000.0 and hi == 3000.0

    # An occupied overflow bucket makes the mean unbounded above, and saying so
    # beats picking a number for it.
    h2 = [0] * 16
    h2[15] = 1
    lo2, hi2 = ls.mean_bounds(h2)
    assert hi2 is None
    assert ls.mean_bounds([0] * 16) is None


def test_describe_bucket_reads_sensibly():
    assert ls.describe_bucket(0) == "0.0-1.0 ms"
    assert ls.describe_bucket(2) == "2.0-3.0 ms"
    assert ls.describe_bucket(15) == ">200 ms"


