def test_capture_round_trip_keeps_the_host_timestamp_and_the_raw_frame():
    raw = fr.encode(src=1, dst=2, opcode=fr.Op.HEARTBEAT, payload=bytes(48))
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "cap.jsonl"
        with CaptureWriter(path) as w:
            w.write_frame(node_id=258, direction="rx", raw=raw,
                          peer_mac="24:6f:28:ab:cd:ef", rssi=-70,
                          node_ts_us=999, host_ts=1_700_000_000.5)
            w.write_record("link", {"node": 258, "peer": 9}, host_ts=1_700_000_001.0)
            w.write_log("I (1) pot.m0: hello", host_ts=1_700_000_002.0)

        rows = list(read_capture(path))
        assert len(rows) == 3
        # section 7.6: host timestamp, direction, raw frame.
        assert rows[0]["host_ts"] == 1_700_000_000.5
        assert rows[0]["dir"] == "rx"
        assert bytes.fromhex(rows[0]["raw"]) == raw
        # The node's own clock is kept too, and labelled as the node's.
        assert rows[0]["node_ts_us"] == 999
        assert rows[1]["rec"] == "link" and rows[1]["peer"] == 9
        assert rows[2]["rec"] == "log"

        # A capture must be re-readable as a frame stream.
        assert fr.parse(bytes.fromhex(rows[0]["raw"])).opcode == fr.Op.HEARTBEAT


def test_capture_rotates_by_size():
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "cap.jsonl"
        with CaptureWriter(path, rotate_bytes=512) as w:
            for i in range(200):
                w.write_record("node", {"node": 1, "i": i})
        files = sorted(p.name for p in Path(tmp).iterdir())
        assert len(files) > 1, files
        assert "cap.jsonl" in files
        total = sum(len(list(read_capture(Path(tmp) / f))) for f in files)
        assert total == 200


def test_capture_survives_a_truncated_final_line():
    # A soak that ends in a power cut leaves a half-written line. Everything before
    # it is still worth having.
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "cap.jsonl"
        with CaptureWriter(path) as w:
            w.write_record("node", {"node": 1})
            w.write_record("node", {"node": 2})
        with open(path, "a", encoding="utf-8") as fh:
            fh.write('{"host_ts":1.0,"kind":"nod')
        rows = list(read_capture(path))
        assert len(rows) == 2


def test_compressed_capture():
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "cap.jsonl"
        with CaptureWriter(path, compress=True) as w:
            w.write_record("node", {"node": 7})
        written = list(Path(tmp).iterdir())
        assert written and written[0].suffix == ".gz"
        assert list(read_capture(written[0]))[0]["node"] == 7


