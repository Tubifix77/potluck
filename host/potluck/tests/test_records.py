"""Tests for the record parser, the histogram helpers and the capture writer.

fixtures/stats_sample.jsonl is generated by the C++ test binary:

    build/tests/pot_tests.exe --emit-fixtures host/potluck/tests/fixtures

so these tests run against exactly the bytes a board emits, not against a
description of them. Regenerate it whenever stats_json.cpp changes -- and if a
test here then fails, the format changed and potluck-capture has to be updated to
match, which is the point.

Run with:  python -m pytest host/potluck/tests -q
       or:  python host/potluck/tests/test_records.py
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from potluck import frame as fr  # noqa: E402
from potluck import link_stats as ls  # noqa: E402
from potluck.capture import CaptureWriter, read_capture  # noqa: E402
from potluck.live import Monitor  # noqa: E402
from potluck.records import FrameRecord, LogLine, Record, RecordStream, ppm_to_percent  # noqa: E402

FIXTURE = Path(__file__).parent / "fixtures" / "stats_sample.jsonl"


def _fixture_lines() -> list[str]:
    assert FIXTURE.exists(), (
        f"{FIXTURE} is missing. Generate it with:\n"
        "  build/tests/pot_tests.exe --emit-fixtures host/potluck/tests/fixtures"
    )
    return [ln for ln in FIXTURE.read_text(encoding="utf-8").splitlines() if ln.strip()]


