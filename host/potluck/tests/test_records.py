def test_a_truncated_line_is_counted_and_skipped_not_guessed_at():
    stream = RecordStream()
    good = _fixture_lines()[1]
    item = stream.feed(good[: len(good) // 2])
    assert isinstance(item, LogLine)  # kept as evidence, not parsed
    assert stream.stats.bad_json == 1
    assert stream.stats.records == 0

    # And the next good line still parses: one bad line must not poison the stream.
    assert isinstance(stream.feed(good), Record)


def test_node_log_lines_pass_through():
    stream = RecordStream()
    item = stream.feed("I (1234) pot.m0: peer 0xcdef declared DEAD after 6 misses")
    assert isinstance(item, LogLine)
    assert stream.stats.logs == 1
    assert stream.feed("") is None
    assert stream.feed("   ") is None


def test_json_that_is_not_one_of_our_records():
    stream = RecordStream()

    # An object without a "t" field looked like a record and was not one, so it
    # counts as malformed: something upstream is emitting the wrong shape.
    assert isinstance(stream.feed('{"no_type_field":1}'), LogLine)
    assert stream.stats.bad_json == 1

    # A line that never claimed to be a record is just text. Counting it as
    # malformed would make the bad_json figure useless for spotting a real
    # problem, because a node's log would inflate it constantly.
    assert isinstance(stream.feed("[1,2,3]"), LogLine)
    assert stream.stats.bad_json == 1
    assert stream.stats.logs == 1


def test_frame_records_decode_and_bad_ones_are_kept_with_a_reason():
    raw = fr.encode(src=1, dst=2, opcode=fr.Op.HEARTBEAT, payload=bytes(48), ack_req=True)
    stream = RecordStream()
    item = stream.feed(json.dumps({
        "t": "frame", "at_us": 12345, "dir": "rx",
        "peer": "24:6f:28:ab:cd:ef", "rssi": -70, "len": len(raw), "raw": raw.hex(),
    }))
    assert isinstance(item, FrameRecord)
    assert item.decoded is not None
    assert item.decoded.opcode == fr.Op.HEARTBEAT
    assert item.direction == "rx" and item.rssi == -70
    assert item.error is None

    # A frame the node rejected still belongs in the capture, with its reason.
    bad = stream.feed(json.dumps({"t": "frame", "dir": "rx", "raw": "00" * 20}))
    assert isinstance(bad, FrameRecord)
    assert bad.decoded is None
    assert bad.error and "bad_magic" in bad.error
    assert stream.stats.bad_frames == 1

    # Non-hex must not raise.
    ugly = stream.feed(json.dumps({"t": "frame", "dir": "tx", "raw": "not-hex"}))
    assert isinstance(ugly, FrameRecord) and ugly.raw == b""


